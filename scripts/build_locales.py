def main():
    with open("ui/locales.json", "r", encoding="utf-8") as f:
        data = json.load(f)

    def clean_brand(s):
        return (s.replace("ClickPulse", "TypeCount")
                 .replace("endNone/ClickPulse", "Amirmpm/typeCount")
                 .replace("events.sqlite3", "typecount.sqlite3"))

    cleaned = {}
    for loc, mp in data.items():
        new_mp = {k: clean_brand(v) for k, v in mp.items()}
        for k, v in EXTRA_EN.items():
            new_mp.setdefault(k, v)
        cleaned[loc] = new_mp

    # Build complete Persian (fa) inheriting report_prompt English fallback where English AI prompt is expected
    fa_map = dict(cleaned["en"])
    fa_map.update(FA_BASE)
    cleaned["fa"] = fa_map

    with open("ui/locales.json", "w", encoding="utf-8") as f:
        json.dump(cleaned, f, ensure_ascii=False, indent=2)
    print(f"Updated ui/locales.json: locales={list(cleaned.keys())}, en_keys={len(cleaned['en'])}, fa_keys={len(cleaned['fa'])}")

if __name__ == "__main__":
    main()
